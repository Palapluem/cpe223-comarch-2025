#include <stdio.h>

int main()
{
	int a,b,c,d,e;
	
	// แก้ไข Data Hazard โดยการ Reordering (สลับลำดับคำสั่ง)
    // นำคำสั่งที่ไม่เกี่ยวข้องกันมาแทรกระหว่างคำสั่งที่มี Dependency

	a = 10;
	b = 20;       // ย้าย b=20 มาแทรก เพื่อให้ a มีเวลาเขียนลง Register ก่อนถูกเรียกใช้ใน c
	c = a+30;     
	d = b+20;     // d รอ b ซึ่งทำเสร็จไปแล้วข้างบน
	
	e = a+b+c+d;  // ถึงตรงนี้ ข้อมูลทุกตัวพร้อมหมดแล้ว

	return e;
}